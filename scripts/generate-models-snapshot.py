"""Generate the offline catalogue from the pinned SDK's embedded models.dev snapshot."""
import argparse
import ast
import base64
import gzip
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sdk = root / "packages/ai/node_modules/@nikcli-ai/sdk-next"
source = (sdk / "index.js").read_text()
anchor = source.index("async function get()", source.index("var GPT_RESERVE_ID"))
start = source.index("const json = await ", anchor) + len("const json = await ")
assert source[start] in "\"'", "The SDK snapshot is no longer a static string; update this generator."
end = start + 1
while end < len(source):
    if source[end] == "\\":
        end += 2
        continue
    if source[end] == source[start]:
        break
    end += 1
# literal_eval decodes only a string literal. No installed JavaScript is executed.
raw = ast.literal_eval(source[start:end + 1]).encode()
catalogue = json.loads(raw)
assert len(catalogue) >= 20
assert all(isinstance(p, dict) and isinstance(p.get("models"), dict) for p in catalogue.values())
version = json.loads((sdk / "package.json").read_text())["version"]
models = sum(len(p["models"]) for p in catalogue.values())
encoded = base64.b64encode(gzip.compress(raw, mtime=0)).decode()
chunks = [encoded[i:i + 160] for i in range(0, len(encoded), 160)]
output = (
    f"// Generated by scripts/generate-models-snapshot.py from @nikcli-ai/sdk-next {version}.\n"
    f"// {len(catalogue)} providers, {models} models; source SHA-256: {hashlib.sha256(raw).hexdigest()}.\n"
    "// Public model metadata only. Regenerate this file when the pinned SDK changes.\n"
    'import { gunzipSync } from "node:zlib"\n\n'
    f"export const BUNDLED_PROVIDER_COUNT = {len(catalogue)}\n"
    f"export const BUNDLED_MODEL_COUNT = {models}\n"
    "const encoded = [\n" + "".join(f'  "{chunk}",\n' for chunk in chunks) + "].join(\"\")\n\n"
    'export const bundledCatalogue = (): string => gunzipSync(Buffer.from(encoded, "base64")).toString("utf8")\n'
)
target = root / "packages/ai/src/nikcli/models-snapshot.ts"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    if not target.exists() or target.read_text() != output:
        raise SystemExit("The bundled catalogue is stale. Run python3 scripts/generate-models-snapshot.py")
else:
    target.write_text(output)
print(f"Bundled nikcli catalogue: {len(catalogue)} providers, {models} models ({len(encoded)} encoded bytes)")
