#!/usr/bin/env bun
/**
 * The Homebrew cask for the desktop application.
 *
 * Nikcli publishes a Homebrew formula for its CLI in `script/publish-registries.ts`; the
 * cadcamfun counterpart is a *cask*, because what is distributed is a macOS application
 * bundle, not a command-line tool. The cask is generated from the checksums the release
 * build already produced, so the digest in the cask is the digest that was verified when
 * the installer was staged.
 *
 * The cask is optional: without a tap repository and a token the release still completes,
 * it simply does not advertise a `brew install` route.
 */

import { $ } from "bun";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { parseChecksums, captureCommand } from "./release-helpers.ts";

export interface CaskEntry {
  /** `arm64` or `x64`. */
  arch: "arm64" | "x64";
  /** The download URL of the `.dmg`. */
  url: string;
  /** The SHA-256 of the `.dmg`, lowercase hex. */
  sha256: string;
}

export interface CaskInput {
  version: string;
  /** `owner/name` of the repository the release lives in. */
  repository: string;
  entries: readonly CaskEntry[];
  /** The application name inside the `.app` bundle. */
  appName?: string;
  /** The name of the cask in the tap. */
  token?: string;
}

/**
 * Render the cask.
 *
 * The two macOS architectures are published as separate platform releases, so the cask
 * picks the right one per machine with `on_arch_conditional`.
 */
export function renderCask(input: CaskInput): string {
  if (input.entries.length === 0) throw new Error("The cask needs at least one macOS build");
  const appName = input.appName ?? "CADCAM FUN";
  const token = input.token ?? "cadcamfun";
  const order: readonly ("arm64" | "x64")[] = ["arm64", "x64"];
  const entries = [...input.entries].sort((a, b) => order.indexOf(a.arch) - order.indexOf(b.arch));
  const arm = entries.find((entry) => entry.arch === "arm64");
  const intel = entries.find((entry) => entry.arch === "x64");

  const block = (entry: CaskEntry | undefined, condition: string | null): string[] => {
    if (entry === undefined) return [];
    const lines = [`    if ${condition}`, `      url "${entry.url}"`, `      sha256 "${entry.sha256}"`];
    if (condition !== null) lines.push("    end");
    return lines;
  };

  const arch: string[] = [];
  if (arm !== undefined && intel !== undefined) {
    arch.push("  on_arch_conditional do");
    arch.push(...block(arm, "Hardware::CPU.arm?"));
    arch.push("    else");
    arch.push(...block(intel, null));
    arch.push("    end");
    arch.push("  end");
  } else {
    const only = entries[0];
    if (only === undefined) throw new Error("The cask needs at least one macOS build");
    arch.push(...block(only, null).map((line) => `  ${line.trimStart()}`));
  }

  return [
    "# typed: false",
    "# frozen_string_literal: true",
    "",
    "# This file was auto-generated by the CADCAM FUN release pipeline. DO NOT EDIT.",
    `cask "${token}" do`,
    `  version "${input.version}"`,
    "",
    ...arch,
    "",
    `  name "${appName}"`,
    `  desc "CAD/CAM desktop application"`,
    `  homepage "https://github.com/${input.repository}"`,
    "",
    `  app "${appName}.app"`,
    "",
    "  # The bundled sidecar is a Bun binary, which needs a recent macOS on every architecture.",
    '  depends_on macos: ">= :ventura"',
    "end",
    "",
  ].join("\n");
}

/**
 * The `.dmg` of a platform release, with its digest.
 *
 * The checksums come from the `SHA256SUMS` the build wrote and the release staging
 * verified, so the cask can never advertise a digest that was not checked.
 */
export function selectDmg(
  checksums: string,
  triple: string,
): { name: string; digest: string } {
  const entries = parseChecksums(checksums);
  const candidates = entries.filter((entry) => entry.name.startsWith(`${triple}--`) && entry.name.toLowerCase().endsWith(".dmg"));
  if (candidates.length !== 1) {
    throw new Error(`Expected exactly one ${triple} .dmg in the release checksums, found ${candidates.length}`);
  }
  const entry = candidates[0];
  if (entry === undefined) throw new Error(`Missing ${triple} .dmg in the release checksums`);
  return { name: entry.name, digest: entry.digest };
}

/** The cask entries of a release, read from the platform releases' checksum files. */
export async function collectCaskEntries(options: {
  tag: string;
  repository: string;
  platforms: readonly { triple: string; arch: "arm64" | "x64"; slug: string }[];
}): Promise<CaskEntry[]> {
  const entries: CaskEntry[] = [];
  for (const platform of options.platforms) {
    const directory = await mkdtemp(join(tmpdir(), "cadcam-cask-"));
    try {
      const download = await captureCommand(["gh", "release", "download", `${options.tag}-${platform.slug}`, "--pattern", "SHA256SUMS", "--repo", options.repository, "--dir", directory]);
      if (download.code !== 0) throw new Error(`Cannot read the checksums of ${options.tag}-${platform.slug}: ${download.stderr.trim()}`);
      const checksums = await readFile(join(directory, "SHA256SUMS"), "utf8");
      const dmg = selectDmg(checksums, platform.triple);
      entries.push({
        arch: platform.arch,
        sha256: dmg.digest,
        url: `https://github.com/${options.repository}/releases/download/${options.tag}-${platform.slug}/${encodeURIComponent(dmg.name)}`,
      });
    } finally {
      await rm(directory, { recursive: true, force: true });
    }
  }
  return entries;
}

export interface PublishCaskOptions {
  repository: string;
  version: string;
  entries: readonly CaskEntry[];
  /** `owner/name` of the tap repository. */
  tap: string;
  /** The branch of the tap the cask is committed to. */
  branch?: string;
  /** The token used to push to the tap. */
  token: string;
  /** Where the tap is cloned; a temporary directory when omitted. */
  workdir?: string;
}

/**
 * Write the cask into the tap repository and push it.
 *
 * The tap is cloned, the cask file is replaced, and the change is committed with the
 * release version in the message — the same shape as nikcli's formula publish.
 */
export async function publishCask(options: PublishCaskOptions): Promise<string> {
  const cask = renderCask({ version: options.version, repository: options.repository, entries: options.entries });
  const directory = options.workdir ?? (await mkdtemp(join(tmpdir(), "cadcam-tap-")));
  const owns = options.workdir === undefined;
  try {
    await $`rm -rf ${directory}`.nothrow();
    const clone = await captureCommand(["git", "clone", "--depth", "1", "--branch", options.branch ?? "main", `https://x-access-token:${options.token}@github.com/${options.tap}.git`, directory]);
    if (clone.code !== 0) throw new Error(`Cannot clone the tap ${options.tap}: ${clone.stderr.trim()}`);
    const file = join(directory, "cadcamfun.rb");
    await writeFile(file, cask, "utf8");
    await $`git -c user.name=release-bot -c user.email=release-bot@users.noreply.github.com add cadcamfun.rb`.cwd(directory);
    const commit = await $`git -c user.name=release-bot -c user.email=release-bot@users.noreply.github.com commit -m "CADCAM FUN ${options.version}"`.nothrow().cwd(directory);
    // An unchanged cask means the tap is already up to date; that is not a failure.
    if (commit.exitCode !== 0) {
      const message = commit.stderr.toString() + commit.stdout.toString();
      if (!/nothing to commit|no changes added/i.test(message)) throw new Error(`Cannot commit the cask: ${message.trim()}`);
      return file;
    }
    const push = await captureCommand(["git", "push", "origin", `HEAD:${options.branch ?? "main"}`], { cwd: directory });
    if (push.code !== 0) throw new Error(`Cannot push the cask: ${push.stderr.trim()}`);
    return file;
  } finally {
    if (owns) await rm(directory, { recursive: true, force: true });
  }
}
