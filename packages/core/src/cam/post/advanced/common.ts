/**
 * Dialect-neutral passes (legacy "COMMON OPTIMIZATION FUNCTIONS") and the generic validator.
 * Used for Siemens, Mazak, Okuma and Generic; Haas goes through the Fanuc path.
 */
import type { Validation } from "./options.ts"
import { codePart, extractCoordinates, has } from "./text.ts"

/** Collapses three or more consecutive empty lines to two. */
export const removeExcessEmptyLines = (code: string): string => code.replace(/\n{3,}/g, "\n\n")

/** Drops comments, keeping the structural ones (`OPERATION`, `SETUP`, `BEGIN`, `END`). */
export const removeComments = (code: string): string => {
  const result: string[] = []
  for (const original of code.split("\n")) {
    if (original.trim().startsWith(";") && (original.includes("OPERATION") || original.includes("SETUP") || original.includes("BEGIN") || original.includes("END"))) {
      result.push(original)
      continue
    }
    const line = original.replace(/\s*;.*$/, "")
    if (line.trim() !== "") result.push(line)
  }
  return result.join("\n")
}

/** Drops rapid moves that go where the tool already is. */
export const optimizeRapidMovements = (code: string): string => {
  const result: string[] = []
  let lastX: number | null = null
  let lastY: number | null = null
  let lastZ: number | null = null

  for (const raw of code.split("\n")) {
    const line = raw.trim()
    if (line === "" || line.startsWith(";")) {
      result.push(line)
      continue
    }
    if (has(line, "G", 0)) {
      const coords = extractCoordinates(codePart(line))
      const xChanged = coords.x !== undefined && (lastX === null || Math.abs(coords.x - lastX) > 0.001)
      const yChanged = coords.y !== undefined && (lastY === null || Math.abs(coords.y - lastY) > 0.001)
      const zChanged = coords.z !== undefined && (lastZ === null || Math.abs(coords.z - lastZ) > 0.001)
      if (coords.x !== undefined) lastX = coords.x
      if (coords.y !== undefined) lastY = coords.y
      if (coords.z !== undefined) lastZ = coords.z
      if (!xChanged && !yChanged && !zChanged) continue
    } else {
      // A feed move or a cycle ends the "last rapid position" assumption for the axes it names.
      const coords = extractCoordinates(codePart(line))
      if (coords.x !== undefined) lastX = coords.x
      if (coords.y !== undefined) lastY = coords.y
      if (coords.z !== undefined) lastZ = coords.z
    }
    result.push(line)
  }
  return result.join("\n")
}

const stripWord = (line: string, letter: string, n: number): string =>
  line.replace(new RegExp(`(?<![A-Za-z0-9.])${letter}0*${n}(?!\\d|\\.\\d)\\s+`), "")

const MOTION = [0, 1, 2, 3] as const

/** Removes G-words that repeat the active modal state (motion, plane, units, distance mode, tool compensation). */
export const consolidateGCodes = (code: string): string => {
  const result: string[] = []
  const state = { motion: -1, plane: -1, unit: -1, coord: -1, comp: -1 }

  const dedupe = (line: string, key: keyof typeof state, codes: ReadonlyArray<number>): string => {
    let out = line
    let seen = -1
    for (const g of codes) if (has(line, "G", g)) { seen = g; break }
    if (seen < 0) return out
    if (state[key] === seen) out = stripWord(out, "G", seen)
    state[key] = seen
    return out
  }

  for (const raw of code.split("\n")) {
    let line = raw.trim()
    if (line === "" || line.startsWith(";")) {
      result.push(line)
      continue
    }
    line = dedupe(line, "motion", MOTION)
    line = dedupe(line, "plane", [17, 18, 19])
    line = dedupe(line, "unit", [20, 21])
    line = dedupe(line, "coord", [90, 91])
    line = dedupe(line, "comp", [40, 41, 42])
    result.push(line)
  }
  return result.join("\n")
}

/** Adds the "optimised by the advanced post-processor" banner unless one is already in the first lines. */
export const addGenericHeader = (code: string, controllerName: string, now: Date): string => {
  const lines = code.split("\n")
  for (let i = 0; i < Math.min(10, lines.length); i++) {
    if (lines[i]!.includes("Generated by") || lines[i]!.includes("Post-processor")) return code
  }
  const header = [
    "% ",
    "; " + "=".repeat(50),
    "; G-code ottimizzato generato dal Post-processor avanzato",
    "; Controller: " + controllerName,
    "; Data: " + now.toISOString().split("T")[0],
    "; " + "=".repeat(50),
    ""
  ]
  return header.join("\n") + "\n" + code
}

/** Validation of dialect-neutral G-code: moves without coordinates, arcs without centre/radius. */
export const validateGeneric = (code: string): Validation => {
  const errors: string[] = []
  const warnings: string[] = []
  const lines = code.split("\n")

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!.trim()
    if (line === "" || line.startsWith(";")) continue
    const body = codePart(line)
    const isArc = has(body, "G", 2) || has(body, "G", 3)
    const isMove = has(body, "G", 0) || has(body, "G", 1) || isArc

    if (isMove && !/[XYZ][-\d.]/.test(body)) warnings.push(`Linea ${i + 1}: Comando di movimento senza coordinate`)
    if (isArc && !/[IJR][-\d.]/.test(body)) errors.push(`Linea ${i + 1}: Comando arco senza parametri centro o raggio`)
  }
  return { isValid: errors.length === 0, errors, warnings }
}
