/**
 * The parity scorecard (spec 55 §5, E3): each capability's level from its declared state, its test evidence and its corpus
 * subset. A level is never written by hand; this module is the only place that turns evidence into one.
 *   0 absent      open, or nothing in the repository tests it
 *   1 partial     partial in the ledger, with test evidence
 *   2 functional  built in the ledger, with test evidence
 *   3 robust      2, and every corpus entry naming the capability passed (within budget) in a complete corpus run
 *   4 qualified   3, an independent oracle and a qualification record: none exists yet, so no row reaches it
 */
import { existsSync } from "node:fs"
import { join } from "node:path"
import type { EntryResult, CorpusEntry } from "./runner.ts"

export interface VendorExpectation { readonly expectation: string; readonly url: string; readonly date: string }

export interface Capability {
  readonly id: string
  readonly area: string
  readonly title: string
  readonly source: string
  readonly state: "open" | "partial" | "built"
  readonly evidence: ReadonlyArray<string>
  readonly vendors?: Partial<Record<"fusion360" | "solidworks" | "creo" | "hypermill", VendorExpectation>>
}

export interface CorpusReport { readonly generatedAt: string; readonly complete: boolean; readonly results: ReadonlyArray<EntryResult> }

export interface Row {
  readonly capability: Capability
  readonly level: 0 | 1 | 2 | 3
  /** Corpus entries naming the capability, and how many of them passed. */
  readonly corpus: { readonly entries: number; readonly passed: number } | undefined
  readonly why: string
}

export const VENDORS = [["fusion360", "Fusion 360"], ["solidworks", "SolidWorks"], ["creo", "Creo"], ["hypermill", "hyperMILL"]] as const

export const scoreRows = (
  capabilities: ReadonlyArray<Capability>,
  corpus: ReadonlyArray<CorpusEntry>,
  report: CorpusReport | undefined,
  root: string
): ReadonlyArray<Row> => capabilities.map((capability) => {
  const missing = capability.evidence.filter((file) => !existsSync(join(root, file)))
  const subset = corpus.filter((e) => e.capabilities.includes(capability.id))
  const results = report?.complete === true ? subset.map((e) => report.results.find((r) => r.id === e.id)) : undefined
  const passed = results?.filter((r) => r?.outcome === "pass").length ?? 0
  const corpusCell = subset.length === 0 ? undefined : { entries: subset.length, passed }
  if (capability.state === "open") return { capability, level: 0, corpus: corpusCell, why: "open in the ledger" }
  if (capability.evidence.length === 0 || missing.length > 0) {
    return { capability, level: 0, corpus: corpusCell, why: missing.length > 0 ? `evidence missing: ${missing.join(", ")}` : "no test evidence" }
  }
  if (capability.state === "partial") return { capability, level: 1, corpus: corpusCell, why: "partial in the ledger" }
  if (subset.length === 0) return { capability, level: 2, corpus: corpusCell, why: "no corpus entry names it" }
  if (results === undefined) return { capability, level: 2, corpus: corpusCell, why: "no complete corpus run" }
  const notPassed = subset.flatMap((e, i) => (results[i]?.outcome === "pass" ? [] : [`${e.id}: ${results[i]?.outcome ?? "not run"}`]))
  return notPassed.length === 0
    ? { capability, level: 3, corpus: corpusCell, why: `all ${subset.length} corpus entries pass within budget` }
    : { capability, level: 2, corpus: corpusCell, why: `corpus: ${notPassed.join(", ")}` }
})

const LEVEL_NAMES = ["0 absent", "1 partial", "2 functional", "3 robust", "4 qualified"] as const

export const renderScorecard = (rows: ReadonlyArray<Row>, report: CorpusReport | undefined, generatedAt: string): string => {
  const counts = [0, 1, 2, 3, 4].map((l) => rows.filter((r) => r.level === l).length)
  const vendorCell = (c: Capability, key: (typeof VENDORS)[number][0]) => {
    const v = c.vendors?.[key]
    return v === undefined ? "—" : `${v.expectation} ([source](${v.url}), ${v.date})`
  }
  const lines = [
    "# Parity scorecard",
    "",
    `Generated by \`bun run scorecard\` on ${generatedAt} from \`packages/core/test/corpus/parity.json\`, the corpus manifest and ${report === undefined ? "**no corpus report**" : `the corpus report of ${report.generatedAt}${report.complete ? "" : " (**incomplete run**: no level 3)"}`}. Do not edit by hand. Rules: [spec 55 §5](../55-evidence-performance-qualification.md); states: [spec 57](../57-parity-ledger-2026-10-25.md).`,
    "",
    "The word *parity* may be used only for a row at level 3 or higher, naming the row. A level-3 row passed **this** corpus subset, which is small: it bounds the failure rate on these parts, nothing more. Vendor columns hold a capability description from public documentation with its source; `—` means not researched yet. Evidence tests are checked to exist; that they pass is CI's job.",
    "",
    `Levels: ${LEVEL_NAMES.map((n, l) => `${n}: ${counts[l]}`).join(" · ")}`,
    "",
    `| Capability | Area | Level | Corpus | Why | ${VENDORS.map(([, name]) => name).join(" | ")} |`,
    `|---|---|---|---|---|${VENDORS.map(() => "---").join("|")}|`,
    ...rows.map((r) => `| \`${r.capability.id}\` ${r.capability.title} (${r.capability.source}) | ${r.capability.area} | ${LEVEL_NAMES[r.level]} | ${r.corpus === undefined ? "—" : `${r.corpus.passed}/${r.corpus.entries}`} | ${r.why} | ${VENDORS.map(([key]) => vendorCell(r.capability, key)).join(" | ")} |`)
  ]
  return `${lines.join("\n")}\n`
}
